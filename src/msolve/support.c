/* Support of a unit ideal over a prime field.
 *
 * When the input generators g_1, ..., g_m generate the unit ideal modulo
 * the prime p, unit_support finds a subset S of them which still does, and
 * which is 1-minimal: removing any single element of S loses the unit, at
 * the degree bound below.  Such a support is the input for computing a
 * small certificate 1 = sum_{i in S} c_i g_i, e.g. by lifting over Q.
 *
 * First the smallest degree D is determined at which the Groebner basis of
 * all generators, truncated at degree D, contains a constant.  Every later
 * test of a subset runs F4 truncated at D: a subset whose truncated basis
 * has a constant generates the unit ideal; one whose truncated basis does
 * not is treated as not generating it, which may keep more generators than
 * needed but never fewer.  So every subset kept is verified unit mod p.
 *
 * The subset is found by taking the shortest prefix of the generators,
 * sorted by their number of terms, that is unit, and then removing chunks
 * of it as long as the rest stays unit (delta debugging). */

#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef struct {
    data_gens_ff_t *gens;
    const int64_t *start;   /* first term of each generator */
    int32_t nr_threads;
    int32_t la_option;
    int32_t initial_hts;
    int32_t max_pairs;
    int32_t update_ht;
    int64_t tests;
} support_ctx_t;

/* Is the ideal generated by the n generators sel[0..n-1] the unit ideal,
 * as seen by F4 truncated at degree maxdeg (0: no truncation)?
 * On a positive answer *degp is set to the largest degree reached. */
static int support_is_unit(
        support_ctx_t *ctx,
        const int32_t *sel,
        const int32_t n,
        const int32_t maxdeg
        )
{
    data_gens_ff_t *gens = ctx->gens;
    const int32_t nv = gens->nvars;
    int64_t nterms   = 0;
    int32_t k;

    ctx->tests++;
    if (n == 0) {
        return 0;
    }
    for (k = 0; k < n; ++k) {
        nterms += gens->lens[sel[k]];
    }
    int32_t *lens = (int32_t *)malloc((size_t)n * sizeof(int32_t));
    int32_t *exps = (int32_t *)malloc((size_t)nterms * nv * sizeof(int32_t));
    int32_t *cfs  = (int32_t *)malloc((size_t)nterms * sizeof(int32_t));
    if (lens == NULL || exps == NULL || cfs == NULL) {
        fprintf(ERRSTREAM, "msolve: out of memory in unit support search\n");
        exit(75);
    }
    int64_t t = 0;
    for (k = 0; k < n; ++k) {
        const int32_t g  = sel[k];
        const int64_t s  = ctx->start[g];
        lens[k] = gens->lens[g];
        memcpy(exps + t * nv, gens->exps + s * nv,
                (size_t)gens->lens[g] * nv * sizeof(int32_t));
        memcpy(cfs + t, gens->cfs + s, (size_t)gens->lens[g] * sizeof(int32_t));
        t += gens->lens[g];
    }

    bs_t *bs  = NULL;
    ht_t *bht = NULL;
    md_t *st  = NULL;
    int unit  = 0;

    int ok = initialize_gba_input_data(&bs, &bht, &st, lens, exps, (void *)cfs,
            gens->field_char, 0 /* DRL */, 0, nv, n, 0, ctx->initial_hts,
            ctx->nr_threads, ctx->max_pairs, ctx->update_ht, ctx->la_option,
            0, 1 /* reduce_gb */, 0, 0, 0 /* info_level */);
    if (ok == 1) {
        int32_t err = 0;
        st->max_gb_degree = maxdeg > 0 ? maxdeg : INT32_MAX;
        bs_t *res = core_gba(bs, st, &err, gens->field_char);
        if (res != NULL && err == 0) {
            unit = res->constant == 1;
            /* F4 ran in place over the prime field: res owns the table */
            free_shared_hash_data(res->ht);
            free_basis(&res);
        }
        free_meta_data(&st);
    } else if (st != NULL) {
        free_meta_data(&st);
    }
    free(lens);
    free(exps);
    free(cfs);
    return unit;
}

static int cmp_int32_support(const void *a, const void *b)
{
    const int32_t x = *(const int32_t *)a;
    const int32_t y = *(const int32_t *)b;
    return (x > y) - (x < y);
}

static int cmp_len(const void *a, const void *b, void *lens)
{
    const int32_t x = ((const int32_t *)lens)[*(const int32_t *)a];
    const int32_t y = ((const int32_t *)lens)[*(const int32_t *)b];
    if (x != y) {
        return x < y ? -1 : 1;
    }
    return *(const int32_t *)a - *(const int32_t *)b;
}

/* Writes the current support to out_file, so that an interrupted search
 * still leaves a verified unit subset behind. */
static void write_support(
        const char *out_file,
        const data_gens_ff_t *gens,
        const int32_t *sel,
        const int32_t n,
        const int32_t m,
        const int32_t D,
        const int64_t tests,
        const int final
        )
{
    int32_t *srt = (int32_t *)malloc((size_t)n * sizeof(int32_t));
    if (srt == NULL) {
        return;
    }
    memcpy(srt, sel, (size_t)n * sizeof(int32_t));
    qsort(srt, (size_t)n, sizeof(int32_t), cmp_int32_support);
    FILE *f = out_file != NULL ? fopen(out_file, "w") : stdout;
    if (f == NULL) {
        fprintf(ERRSTREAM, "Cannot open %s for writing.\n", out_file);
        free(srt);
        return;
    }
    fprintf(f, "#unit support modulo %ld: %d of %d generators, degree %d, %ld tests%s\n",
            (long)gens->field_char, n, m, D, (long)tests,
            final ? "" : " (search not finished, the subset is unit)");
    fprintf(f, "#generators are numbered from 0 in input order\n");
    for (int32_t i = 0; i < n; ++i) {
        fprintf(f, "%d\n", srt[i]);
    }
    if (f != stdout) {
        fclose(f);
    }
    free(srt);
}

int unit_support(
        data_gens_ff_t *gens,
        const int32_t nr_threads,
        const int32_t la_option,
        const int32_t initial_hts,
        const int32_t max_pairs,
        const int32_t update_ht,
        const int32_t info_level,
        const char *out_file
        )
{
    int32_t i, j;
    const int32_t m = gens->ngens;

    if (gens->field_char == 0 || gens->field_char > INT32_MAX
            || gens->cfs == NULL) {
        fprintf(ERRSTREAM,
                "The unit support is computed over prime fields below 2^31 only.\n");
        return 1;
    }
    int64_t *start = (int64_t *)malloc((size_t)(m + 1) * sizeof(int64_t));
    int32_t *sel   = (int32_t *)malloc((size_t)m * sizeof(int32_t));
    int32_t *tmp   = (int32_t *)malloc((size_t)m * sizeof(int32_t));
    if (start == NULL || sel == NULL || tmp == NULL) {
        fprintf(ERRSTREAM, "msolve: out of memory in unit support search\n");
        exit(75);
    }
    start[0] = 0;
    for (i = 0; i < m; ++i) {
        start[i + 1] = start[i] + gens->lens[i];
        sel[i] = i;
    }
    support_ctx_t ctx = { gens, start, nr_threads, la_option, initial_hts,
        max_pairs, update_ht, 0 };

    /* the smallest degree at which all generators give a constant */
    int32_t maxdeg = 0;
    for (i = 0; i < m; ++i) {
        int32_t d = 0;
        for (j = 0; j < gens->lens[i]; ++j) {
            int32_t e = 0;
            for (int32_t v = 0; v < gens->nvars; ++v) {
                e += gens->exps[(start[i] + j) * gens->nvars + v];
            }
            d = e > d ? e : d;
        }
        maxdeg = d > maxdeg ? d : maxdeg;
    }
    if (!support_is_unit(&ctx, sel, m, 0)) {
        fprintf(ERRSTREAM, "The generators do not generate the unit ideal.\n");
        free(start); free(sel); free(tmp);
        return 2;
    }
    int32_t D = maxdeg;
    while (!support_is_unit(&ctx, sel, m, D)) {
        D++;
    }
    if (info_level > 0) {
        fprintf(VERBSTREAM, "unit support: constant found at degree %d\n", D);
    }

    /* shortest unit prefix, generators sorted by number of terms */
    sort_r(sel, (size_t)m, sizeof(int32_t), cmp_len, gens->lens);
    int32_t lo = 1, hi = m;
    while (lo < hi) {
        const int32_t mid = lo + (hi - lo) / 2;
        if (support_is_unit(&ctx, sel, mid, D)) {
            hi = mid;
        } else {
            lo = mid + 1;
        }
    }
    int32_t n = lo;
    if (out_file != NULL) {
        write_support(out_file, gens, sel, n, m, D, ctx.tests, 0);
    }
    if (info_level > 0) {
        fprintf(VERBSTREAM, "unit support: shortest unit prefix %d of %d\n", n, m);
    }

    /* delta debugging: drop chunks while the rest stays unit */
    int32_t parts = 2;
    while (n >= 2) {
        const int32_t chunk = (n + parts - 1) / parts;
        int reduced = 0;
        for (i = 0; i < n; i += chunk) {
            const int32_t e = i + chunk < n ? i + chunk : n;
            int32_t r = 0;
            for (j = 0; j < n; ++j) {
                if (j < i || j >= e) {
                    tmp[r++] = sel[j];
                }
            }
            if (r > 0 && support_is_unit(&ctx, tmp, r, D)) {
                memcpy(sel, tmp, (size_t)r * sizeof(int32_t));
                n = r;
                parts = parts > 2 ? parts - 1 : 2;
                reduced = 1;
                if (out_file != NULL) {
                    write_support(out_file, gens, sel, n, m, D, ctx.tests, 0);
                }
                if (info_level > 0) {
                    fprintf(VERBSTREAM, "unit support: %d generators (%ld tests)\n",
                            n, (long)ctx.tests);
                }
                break;
            }
        }
        if (!reduced) {
            if (parts >= n) {
                break;
            }
            parts = 2 * parts < n ? 2 * parts : n;
        }
    }

    /* report the support in input order, 0-based */
    write_support(out_file, gens, sel, n, m, D, ctx.tests, 1);
    free(start);
    free(sel);
    free(tmp);
    return 0;
}
